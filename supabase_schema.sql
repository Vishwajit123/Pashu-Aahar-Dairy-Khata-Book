-- 1. CREATE CUSTOMERS TABLE (Farmer & Buyer Khata Profiles)
CREATE TABLE IF NOT EXISTS customers (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    phone VARCHAR(20),
    address VARCHAR(255),
    notes VARCHAR(255),
    created_at DATE NOT NULL DEFAULT CURRENT_DATE
);

-- 2. CREATE EXPENSES TABLE (Feed Bags & Dairy Sales Ledger)
CREATE TABLE IF NOT EXISTS expenses (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    expense_name VARCHAR(100) NOT NULL,
    description VARCHAR(255),
    amount NUMERIC(12, 2) NOT NULL CHECK (amount > 0),
    expense_date DATE NOT NULL DEFAULT CURRENT_DATE,
    category VARCHAR(50) NOT NULL,
    mode_of_payment VARCHAR(50) NOT NULL,
    customer_id INTEGER REFERENCES customers(id) ON DELETE SET NULL,
    customer_name VARCHAR(100) DEFAULT 'Walk-in Customer',
    customer_phone VARCHAR(20) DEFAULT '',
    payment_status VARCHAR(20) NOT NULL DEFAULT 'PAID'
);

-- 3. CREATE PERFORMANCE INDEXES
CREATE INDEX IF NOT EXISTS idx_expenses_customer_id ON expenses(customer_id);
CREATE INDEX IF NOT EXISTS idx_expenses_payment_status ON expenses(payment_status);
CREATE INDEX IF NOT EXISTS idx_expenses_date ON expenses(expense_date);
CREATE INDEX IF NOT EXISTS idx_expenses_category ON expenses(category);
CREATE INDEX IF NOT EXISTS idx_customers_phone ON customers(phone);

-- 4. CREATE HELPFUL VIEW FOR CUSTOMER KHATA BALANCE & DUES
CREATE OR REPLACE VIEW view_customer_khata_summary AS
SELECT 
    c.id AS customer_id,
    c.name AS customer_name,
    c.phone,
    c.address,
    COALESCE(SUM(e.amount), 0) AS total_purchases,
    COALESCE(SUM(CASE WHEN e.payment_status = 'PAID' THEN e.amount ELSE 0 END), 0) AS total_paid,
    COALESCE(SUM(CASE WHEN e.payment_status = 'UNPAID' THEN e.amount ELSE 0 END), 0) AS total_unpaid_due,
    COUNT(e.id) AS total_transactions
FROM customers c
LEFT JOIN expenses e ON c.id = e.customer_id
GROUP BY c.id, c.name, c.phone, c.address;

